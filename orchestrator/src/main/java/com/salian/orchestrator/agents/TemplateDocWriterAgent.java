package com.salian.orchestrator.agents;

import com.fasterxml.jackson.databind.JsonNode;
import com.salian.orchestrator.engine.Agent;
import com.salian.orchestrator.engine.ExecutionMode;
import com.salian.orchestrator.engine.StageContext;
import com.salian.orchestrator.engine.StageResult;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Deterministic documentation agent (REAL): renders change notes from the requirement, plan and
 * design artifacts, so the docs always match what was actually planned and designed.
 */
public final class TemplateDocWriterAgent implements Agent {

    @Override
    public String name() {
        return "template-doc-writer";
    }

    @Override
    public ExecutionMode mode() {
        return ExecutionMode.REAL;
    }

    @Override
    public StageResult execute(StageContext ctx) {
        JsonNode requirement = ctx.input("requirement");
        JsonNode plan = ctx.input("plan");
        JsonNode design = ctx.input("design");
        String scenario = ctx.parameter(Scenarios.PARAM_SCENARIO);

        StringBuilder md = new StringBuilder();
        md.append("# Change notes: ").append(scenario).append("\n\n");
        md.append("_Generated by the orchestrator's template doc writer from run `").append(ctx.runId())
                .append("` artifacts._\n\n");
        md.append("## Requirement\n\n").append(requirement.path("summary").asText()).append("\n\n");
        md.append("> ").append(requirement.path("rawText").asText().replace("\n", "\n> ")).append("\n\n");
        section(md, "Acceptance criteria", requirement.path("acceptanceCriteria"));
        section(md, "Out of scope", requirement.path("outOfScope"));
        section(md, "Constraints", requirement.path("constraints"));
        md.append("## API surface\n\n");
        for (JsonNode endpoint : design.path("endpoints")) {
            md.append("- `").append(endpoint.asText()).append("`\n");
        }
        md.append("\nErrors: ").append(design.path("errorModel").asText()).append("\n\n");
        section(md, "Schema migrations", design.path("migrations"));
        section(md, "Configuration prefixes", design.path("configurationPrefixes"));
        md.append("## Plan\n\n");
        for (JsonNode task : plan.path("tasks")) {
            md.append("- **").append(task.path("id").asText()).append("**: ").append(task.path("title").asText());
            if (task.path("dependsOn").size() > 0) {
                md.append(" (after ").append(task.path("dependsOn")).append(")");
            }
            md.append("\n");
        }
        md.append("\n");
        section(md, "Risks", plan.path("risks"));

        String path = Scenarios.PROJECT + "/docs/" + scenario + "-change-notes.md";
        ctx.workspace().write(ctx.stageId(), path, md.toString());
        Map<String, Object> docs = new LinkedHashMap<>();
        docs.put("summary", "Change notes written to " + path);
        docs.put("files", java.util.List.of(path));
        docs.put("generator", "template (deterministic)");
        ctx.output("docs", docs);
        return StageResult.ok((String) docs.get("summary"));
    }

    private static void section(StringBuilder md, String title, JsonNode items) {
        if (items == null || items.isMissingNode() || items.isEmpty()) {
            return;
        }
        md.append("## ").append(title).append("\n\n");
        items.forEach(item -> md.append("- ").append(item.isTextual() ? item.asText() : item.toString()).append("\n"));
        md.append("\n");
    }
}
